import {spawn} from 'node:child_process';
import {mkdtempSync,mkdirSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
const scratch=mkdtempSync(join(tmpdir(),'vibes-app-probe-'));
const env={...process.env,PROBE_PROFILE:join(scratch,'shell'),PROBE_MAIN:process.argv[2]||join(process.env.LOCALAPPDATA,'Programs/arara-vibes/resources/app.asar/dist/main.cjs'),ARARA_VIBES_PROFILE:join(scratch,'host'),ARARA_VIBES_ROOT:scratch,ARARA_VIBES_SESSION_FILE:join(scratch,'session.json'),ARARA_VIBES_HOSTS:join(scratch,'hosts'),ARARA_VIBES_DISABLE_UPDATES:'1',ARARA_DISABLE_COMPANION_DOWNLOAD:'1'};
delete env.ELECTRON_RUN_AS_NODE;
mkdirSync(env.PROBE_PROFILE);writeFileSync(join(env.PROBE_PROFILE,'preferences.json'),JSON.stringify({onboarded:true,launchAtLogin:false}));
console.log(scratch);
const child=spawn(resolve('node_modules/electron/dist/electron.exe'),[resolve('scripts/probe-app.cjs')],{env,stdio:'inherit'});
child.on('exit',code=>{process.exitCode=code});
